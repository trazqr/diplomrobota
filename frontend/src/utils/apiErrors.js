export function apiErrorMessage(error, lang, fallback) {
  const locale = lang === 'en' ? 'en' : 'ua'
  return (
    MESSAGES[locale][error?.code] ||
    fallback ||
    (locale === 'en' ? 'The action failed.' : 'Не вдалося виконати дію.')
  )
}
